"""D-050 + D-052 — the design laws, enforced by the suite.

D-052 (shame-safety): no surface generated by this project may praise,
shame, compare, or end an interaction by proposing the next one. The
specimen is the evidence: eloquent refusal was metabolized as content.
This file is the law's teeth — every future surface is linted here.

D-050 (configuration immutability): config/profile edits are cold-state
acts; a file that changes while the daemon runs is recorded as drift
and never hot-loaded.
"""

import json
import re
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from test_plumbing import DhritiTestCase

ROOT = Path(__file__).resolve().parents[1]

# Praise/shame/comparative phrases that must never appear in any
# surface this software renders. Case-insensitive. Adding a phrase here
# is a design decision; adding it to a surface is a violation.
FORBIDDEN_PHRASES = (
    "great job", "well done", "congrat", "awesome", "amazing",
    "you're doing", "you are doing great", "proud of you",
    "lazy", "pathetic", "embarrass", "disappoint",
    "you failed", "failure rate", "shame on you",
    "streak", "percentile", "better than", "worse than",
    "you're ahead", "you're behind other",
)

EXTENSION_SURFACES = [
    "extension/blocked.html", "extension/blocked.js",
    "extension/blocked.css", "extension/background.js",
    "extension/suppress.js", "extension/config.js",
]


def _strip_html_comments(text: str) -> str:
    return re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)


def _strip_js_comments(text: str) -> str:
    # crude but sufficient: keep string literals, drop // and /* */
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    return re.sub(r"^\s*//.*$", "", text, flags=re.MULTILINE)


class TestShameSafetyExtension(unittest.TestCase):
    """The wall and its scripts: boring, silent, no next move."""

    def test_no_praise_shame_or_comparison_in_surfaces(self):
        for rel in EXTENSION_SURFACES:
            path = ROOT / rel
            self.assertTrue(path.exists(), f"missing surface {rel}")
            text = path.read_text(encoding="utf-8")
            text = _strip_html_comments(text)
            text = _strip_js_comments(text)
            for phrase in FORBIDDEN_PHRASES:
                self.assertNotIn(
                    phrase, text.lower(),
                    f"{rel} renders forbidden phrase: {phrase!r}")

    def test_wall_page_proposes_no_next_interaction(self):
        html = _strip_html_comments(
            (ROOT / "extension/blocked.html").read_text(encoding="utf-8"))
        self.assertNotIn("<a ", html)      # no links out
        self.assertNotIn("<button", html)  # no buttons
        self.assertNotIn("<form", html)    # no forms
        # the only voice is the contract line placeholder
        self.assertIn("line", html)

    def test_no_notification_api_anywhere(self):
        # notifications are engagement surfaces; the wall does not talk
        for rel in EXTENSION_SURFACES:
            text = (ROOT / rel).read_text(encoding="utf-8")
            self.assertNotIn("chrome.notifications", text)

    def test_extension_javascript_parses(self):
        # every surface file must at least be balanced JavaScript
        for rel in EXTENSION_SURFACES:
            if not rel.endswith(".js"):
                continue
            text = (ROOT / rel).read_text(encoding="utf-8")
            self.assertEqual(
                text.count("{"), text.count("}"),
                f"{rel} has unbalanced braces")


class TestShameSafetyReports(DhritiTestCase):
    """The aftermath and the digest: facts, never verdicts."""

    def test_aftermath_output_is_praise_and_shame_free(self):
        from dhriti.aftermath import AftermathService
        self.seal_today()
        day = self.days.ensure_day(self.today)
        self.ledger.record(
            "browser_navigation", source_adapter="extension",
            observed_payload={"url": "https://www.youtube.com",
                              "title": ""})
        self.break_glass.emergency("laptop on fire, literally",
                                   day_id=day["id"])
        report = AftermathService(
            self.db, self.config, self.clock, self.ledger)\
            .day_report(day)
        for phrase in FORBIDDEN_PHRASES:
            self.assertNotIn(phrase, report["markdown"].lower())
            self.assertNotIn(phrase, report["html"].lower())

    def test_digest_output_is_praise_and_shame_free(self):
        from dhriti.review import build_digest
        self.seal_today()
        self.days.ensure_day(self.today)
        text = build_digest(self.db, self.ledger,
                            self.today.isoformat(), clock=self.clock,
                            config=self.config)
        for phrase in FORBIDDEN_PHRASES:
            self.assertNotIn(phrase, text.lower())

    def test_the_taxonomy_and_laws_exist_as_reference(self):
        patterns = (ROOT / "analysis/labels/BEHAVIORAL_PATTERNS.md")\
            .read_text(encoding="utf-8")
        for code in ("P-01", "P-05", "P-10"):
            self.assertIn(code, patterns)
        laws = (ROOT / "docs/DESIGN_LAWS.md").read_text(encoding="utf-8")
        self.assertIn("Shame-safety", laws)
        self.assertIn("Configuration immutability", laws)


class TestConfigImmutability(DhritiTestCase):
    """D-050: edits while running are recorded, never hot-loaded."""

    def test_disk_edit_is_drift_recorded_once(self):
        self.seal_today()
        daemon = self.make_daemon()
        daemon._tick()
        # edit the config on disk while the daemon runs
        (self.home / "dhriti.config.json").write_text(
            json.dumps({"stage_ratio": {"audience_band": [0.25, 0.35]}}),
            encoding="utf-8")
        daemon._check_config_drift()
        events = [e for e in daemon.ledger.events()
                  if e["event_type"] == "config_drift_detected"]
        self.assertEqual(len(events), 1)
        self.assertIn("no hot reload", events[0]["action_taken"])
        # a second check does not duplicate the event
        daemon._check_config_drift()
        events = [e for e in daemon.ledger.events()
                  if e["event_type"] == "config_drift_detected"]
        self.assertEqual(len(events), 1)
        # and the running rules were NOT hot-reloaded
        self.assertEqual(
            daemon.config.get("stage_ratio", {})
            .get("audience_band"), [0.2, 0.3])
        daemon.release_lock()
        daemon.db.close()

    def test_no_edit_no_drift(self):
        self.seal_today()
        daemon = self.make_daemon()
        daemon._check_config_drift()
        daemon._check_config_drift()
        self.assertNotIn(
            "config_drift_detected",
            [e["event_type"] for e in daemon.ledger.events()])
        daemon.release_lock()
        daemon.db.close()


